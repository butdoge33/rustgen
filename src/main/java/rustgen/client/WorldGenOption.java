package rustgen.client;

import net.minecraft.client.Minecraft;
import net.minecraft.client.Option;
import net.minecraft.client.Options;
import net.minecraft.client.gui.components.AbstractWidget;
import net.minecraft.client.gui.components.CycleButton;
import net.minecraft.network.chat.TextComponent;

import rustgen.RustgenConfig;

/**
 * "World Generation: Rust / Java" (Video Settings).
 *
 * Text is built here rather than from assets/rustgen/lang: on 1.18.2 a mod's language
 * files are only loaded when Fabric API is installed, and rustgen must not require it.
 */
public final class WorldGenOption extends Option {
	public static final WorldGenOption INSTANCE = new WorldGenOption();

	private WorldGenOption() {
		super("rustgen.worldgen");
	}

	@Override
	public AbstractWidget createButton(Options options, int x, int y, int width) {
		Minecraft mc = Minecraft.getInstance();
		boolean pt = mc.getLanguageManager().getSelected().getCode().startsWith("pt");
		return CycleButton.booleanBuilder(new TextComponent("Rust"), new TextComponent("Java"))
				.withInitialValue(RustgenConfig.useRust())
				.withTooltip(value -> mc.font.split(new TextComponent(tooltip(value, pt)), 200))
				.create(x, y, width, 20, new TextComponent(pt ? "Geração de Mundo" : "World Generation"),
						(button, value) -> RustgenConfig.setUseRust(value));
	}

	private static String tooltip(boolean rust, boolean pt) {
		if (rust) {
			return pt ? "Novos chunks são gerados pelo gerador de terreno nativo (Rust) do rustgen. Os chunks são idênticos aos do vanilla."
					: "New chunks are generated by rustgen's native (Rust) terrain generator. Chunks are identical to vanilla's.";
		}
		return pt ? "Novos chunks são gerados pelo gerador de terreno do próprio Minecraft (Java)."
				: "New chunks are generated by Minecraft's own (Java) terrain generator.";
	}
}
